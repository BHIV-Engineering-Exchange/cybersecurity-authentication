"""
Export the module's versioned API and event contracts as JSON Schema files into cybercrime/contracts/.

The schemas are generated from the Pydantic models the API actually uses, so code and contract cannot drift apart
silently: test_contract_schemas.py fails if a committed schema differs from the model.
Usage: cd cybercrime/backend && python scripts/export_contract_schemas.py
"""

import json
import os
import sys
from pathlib import Path

os.environ.setdefault("SECRET_KEY", "schema-export-only")
BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

from app.api.v1.endpoints.access import RestoreRequest, RestoreResponse, RevocationRequest, RevocationResponse  # noqa: E402
from app.api.v1.endpoints.authz import AuthzCheckRequest, AuthzCheckResponse  # noqa: E402
from app.api.v1.endpoints.protected_access import ProtectedAccessRequest, ProtectedAccessResponse  # noqa: E402
from app.api.v1.endpoints.threats import SecurityIncidentView  # noqa: E402
from app.api.v1.schemas import IncidentReportRequest, IncidentReportResponse  # noqa: E402
from app.core.canonical_event import CanonicalSecurityEvent  # noqa: E402

OUT = BACKEND.parent / "contracts"

# (file stem, model, version, owner lane, what it is)
CONTRACTS = [
    ("canonical_security_event", CanonicalSecurityEvent, "1.0.0", "Kaushlendra", "Every security event the module records (audit store, logs, TANTRA payload source)"),
    ("authz_check_request", AuthzCheckRequest, "1.0.0", "Kaushlendra", "POST /api/v1/authz/check request"),
    ("authz_check_response", AuthzCheckResponse, "1.0.0", "Kaushlendra", "POST /api/v1/authz/check response"),
    ("access_revocation_request", RevocationRequest, "1.0.0", "Kaushlendra", "POST /api/v1/access/revoke request"),
    ("access_revocation_response", RevocationResponse, "1.0.0", "Kaushlendra", "POST /api/v1/access/revoke response"),
    ("access_restore_request", RestoreRequest, "1.0.0", "Kaushlendra", "POST /api/v1/access/restore request"),
    ("access_restore_response", RestoreResponse, "1.0.0", "Kaushlendra", "POST /api/v1/access/restore response"),
    ("protected_access_request", ProtectedAccessRequest, "1.0.0", "Rajaryan (bridge by Hemanth)", "POST /api/v1/protected/access request"),
    ("protected_access_response", ProtectedAccessResponse, "1.0.0", "Rajaryan (bridge by Hemanth)", "POST /api/v1/protected/access response"),
    ("security_incident", SecurityIncidentView, "1.0.0", "Aryan Dias / Shivam", "GET /api/v1/threats/incidents item"),
    ("incident_report_request", IncidentReportRequest, "1.0.0", "Shivam", "POST /api/v1/incidents/analyze request"),
    ("incident_report_response", IncidentReportResponse, "1.0.0", "Shivam", "POST /api/v1/incidents/analyze response"),
]


def render() -> dict:
    files = {}
    for stem, model, version, owner, what in CONTRACTS:
        schema = model.model_json_schema()
        schema = {"$schema": "https://json-schema.org/draft/2020-12/schema", "$id": f"bhiv-cybersecurity/{stem}/{version}",
                  "x-contract-version": version, "x-owner": owner, "x-description": what, **schema}
        files[f"{stem}.v{version}.schema.json"] = json.dumps(schema, indent=2, sort_keys=True) + "\n"
    index = ["# Contracts (JSON Schema)", "", "Generated by `cybercrime/backend/scripts/export_contract_schemas.py` from the models the "
             "API uses. `cybercrime/backend/test_contract_schemas.py` fails if these files drift from the code.", "",
             "| File | Version | Owner lane | What |", "|---|---|---|---|"]
    index += [f"| `{stem}.v{version}.schema.json` | {version} | {owner} | {what} |" for stem, _, version, owner, what in CONTRACTS]
    files["README.md"] = "\n".join(index) + "\n"
    return files


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in render().items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(CONTRACTS)} schemas to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
